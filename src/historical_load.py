# Importing requests library
import requests

# Importing pandas library
import pandas as pd

"""# Extract"""

# Define monthly extraction periods for initial load
monthly_batches = [
    ("2026-01-01", "2026-02-01"),
    ("2026-02-01", "2026-03-01"),
    ("2026-03-01", "2026-04-01"),
    ("2026-04-01", "2026-05-01"),
    ("2026-05-01", "2026-06-01"),
    ("2026-06-01", "2026-07-01"),
    ("2026-07-01", "2026-08-01")
]


# Create an empty list to store all earthquake records
all_earthquake_data = []

# Loop to extract historical data
for start_date, end_date in monthly_batches:

    print(f"Extracting data from {start_date} to {end_date}")

    # Define the USGS Earthquake API endpoint
    url = (
        "https://earthquake.usgs.gov/fdsnws/event/1/query"
        f"?format=geojson"
        f"&starttime={start_date}"
        f"&endtime={end_date}"
    )

    # Send a GET request to the API
    response = requests.get(url)

    # Raise an exception if the request was unsuccessful
    response.raise_for_status()

    # Parse the API response from JSON into a Python dictionary
    data = response.json()

    # Extract the list of earthquake records from the 'features' key
    earthquake_data = data.get("features", [])

    # Append this month's data to the master list
    all_earthquake_data.extend(earthquake_data)

    print(
        f"Extract completed: {len(earthquake_data)} records retrieved from {start_date} to {end_date}"
    )

# Convert the list of earthquake records into a pandas DataFrame
df = pd.DataFrame(all_earthquake_data)
