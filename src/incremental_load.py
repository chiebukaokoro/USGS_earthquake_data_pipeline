# Function to load data
def earthquake_data_incremental_load(transformed_earthquake_df):

   # Load Initiation Notification
   print("[PIPELINE] Starting incremental load")

   # Define database path
   BASE_DIR = Path(__file__).resolve().parent.parent
   DB_PATH = BASE_DIR / "database" / "earthquake.db"

   # Check database exists
   if not DB_PATH.exists():
    raise FileNotFoundError("Database does not exist. Run historical load first.")

   # Create database connection
   engine = create_engine(f"sqlite:///{DB_PATH}")

   # Retrieve existing earthquake id from the database
   with engine.connect() as connection:
        existing_ids = pd.read_sql(
            "SELECT id FROM earthquakes",
            connection
        )

   # Convert extraced data to set
   existing_ids = set(existing_ids["id"])

   # Keep only new earthquakes
   new_records = transformed_earthquake_df[~transformed_earthquake_df["id"].isin(existing_ids)]

   # Number of duplicate records
   duplicate_count = len(transformed_earthquake_df) - len(new_records)

   # Display for verification
   print(f"[CHECK] {duplicate_count} duplicate records skipped")

   # Append new records to the database
   # Check if there are any new records
   if len(new_records) > 0:
    # Append new record to the database
    with engine.begin() as connection:
      new_records.to_sql(
        "earthquakes",
        con=engine,
        if_exists="append",
        index=False
      )

    # Display for verification
    print(f"[LOAD] {len(new_records)} new records inserted")

   else:
    print("[LOAD] No new records to insert")


def run_incremental_pipeline(reference_date):

    # Extract
    raw_df = extract_earthquake_data(reference_date)


    # Transform
    transformed_df = transform_earthquake_data(raw_df)

    # Load
    earthquake_data_incremental_load(transformed_df)

    # Load Completion Notification
    print("[PIPELINE] Incremental load completed")

run_incremental_pipeline(datetime.today())